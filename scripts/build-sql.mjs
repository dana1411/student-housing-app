// Builds the SQL bundles from db/:
//   src/backend/generated/local.sql      demo mode (runs in the browser with PGlite) and tests
//   supabase/migrations/..._core.sql      the Supabase database
// The app name and key prefix come from app.config.json.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'app.config.json'), 'utf8'));
const read = dir => fs.readdirSync(path.join(root, dir)).filter(f => f.endsWith('.sql')).sort()
  .map(f => `-- >>> ${dir}/${f}\n` + fs.readFileSync(path.join(root, dir, f), 'utf8'));
const fill = s => s.replaceAll('{{APP_NAME}}', cfg.name.replace(/'/g, "''")).replaceAll('{{KEY_PREFIX}}', cfg.keyPrefix);

const core = read('db/core');
const local = fill([...read('db/local').filter(s => s.includes('00_auth_stub')), ...core, ...read('db/local').filter(s => !s.includes('00_auth_stub'))].join('\n'));
const supa = fill([`-- Generated by scripts/build-sql.mjs from db/core and db/supabase. Do not edit by hand.`, ...core, ...read('db/supabase')].join('\n'));

fs.mkdirSync(path.join(root, 'src/backend/generated'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/backend/generated/local.sql'), local);
fs.mkdirSync(path.join(root, 'supabase/migrations'), { recursive: true });
fs.writeFileSync(path.join(root, 'supabase/migrations/20261107000000_core.sql'), supa);
// Capacitor (phone app) settings come from the same file.
fs.writeFileSync(path.join(root, 'capacitor.config.json'), JSON.stringify({
  appId: cfg.appId, appName: cfg.name, webDir: 'dist',
  android: { allowMixedContent: false },
  plugins: { SplashScreen: { launchShowDuration: 1200, backgroundColor: '#1B2A6B', showSpinner: false } }
}, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'public/manifest.webmanifest'), JSON.stringify({
  name: cfg.name, short_name: cfg.name, start_url: './', display: 'standalone',
  background_color: '#1B2A6B', theme_color: '#1B2A6B',
  icons: [{ src: 'icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any maskable' }]
}, null, 2) + '\n');
console.log(`sql: local ${(local.length / 1024).toFixed(0)} KB, supabase ${(supa.length / 1024).toFixed(0)} KB`);
